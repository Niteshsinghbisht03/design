/**
 * Client-side SvgTileParser
 * Decomposes arbitrary vector SVG files into normalized 100x100 colorable tile regions.
 */

export const R = (n, ...e) => ({
  n,
  e: e.map(x => (typeof x === "string" ? [x, ""] : x))
});

export const BG = R("Background", "M0 0H100V100H0Z");

export class SvgTileParser {
  static parse(svgString) {
    const parser = new DOMParser();
    const doc = parser.parseFromString(svgString, "image/svg+xml");
    const svg = doc.documentElement;
    if (svg.nodeName !== "svg" || doc.querySelector("parsererror")) {
      return null;
    }

    // Determine viewBox and dimensions
    let vb = (svg.getAttribute("viewBox") || "").trim().split(/[\s,]+/).map(Number);
    if (vb.length !== 4 || vb.some(isNaN)) {
      const w = parseFloat(svg.getAttribute("width")) || 100;
      const h = parseFloat(svg.getAttribute("height")) || 100;
      vb = [0, 0, w, h];
    }

    const [vx, vy, vw, vh] = vb;
    const maxDim = Math.max(vw, vh) || 100;
    const scale = 100 / maxDim;
    const offsetX = (100 - vw * scale) / 2;
    const offsetY = (100 - vh * scale) / 2;
    const baseTransform = `translate(${offsetX.toFixed(4)} ${offsetY.toFixed(4)}) scale(${scale.toFixed(6)}) translate(${-vx} ${-vy})`;

    // Check for outline groups or elements (generated by AI vectorizer or ink outlines)
    const outlineGroup = doc.querySelector("#ink-outlines, #tile-outlines, g[id*='outline']");
    const outlineElements = new Set();
    if (outlineGroup) {
      outlineGroup.querySelectorAll("path, rect, circle, polygon, polyline, line").forEach(el => outlineElements.add(el));
    }
    // Also check for individual outline paths
    doc.querySelectorAll("#linework, path[id*='linework'], path[id$='-outline'], path[data-name*='Outline']").forEach(el => outlineElements.add(el));

    let outlineOverlay = null;
    if (outlineElements.size > 0) {
      const outlinePaths = [];
      outlineElements.forEach(el => {
        const d = (el.getAttribute("d") || "").trim();
        if (d) outlinePaths.push(d);
      });
      if (outlinePaths.length > 0) {
        outlineOverlay = {
          d: outlinePaths.join(" "),
          transform: baseTransform
        };
      }
    }

    const regions = [BG]; // Region 0: Background
    const elements = svg.querySelectorAll("path, rect, circle, ellipse, polygon, polyline, line");

    elements.forEach(el => {
      // Ignore elements inside defs, clipPath, mask, pattern, symbol, etc.
      if (el.closest("defs, clipPath, mask, pattern, symbol, marker, style")) return;

      // Ignore outline elements so they are not treated as fillable shapes!
      if (outlineElements.has(el) || el.closest("#ink-outlines, #tile-outlines, g[id*='outline']")) return;

      const id = el.getAttribute("id") || "";
      if (id === "linework" || id.endsWith("-outline") || id.includes("outline")) return;

      // Skip full canvas background rect if present, as Region 0 already covers 100x100
      if (id === "background-fill" || el.getAttribute("data-name") === "Background") return;

      const tag = el.tagName.toLowerCase();
      let d = "";
      const getNum = attr => parseFloat(el.getAttribute(attr)) || 0;

      if (tag === "path") {
        d = (el.getAttribute("d") || "").trim();
      } else if (tag === "rect") {
        const x = getNum("x"), y = getNum("y");
        const w = getNum("width"), h = getNum("height");
        // Skip canvas bounding box rects
        if (w >= vw - 1 && h >= vh - 1 && x <= vx + 1 && y <= vy + 1) return;
        const rx = getNum("rx"), ry = getNum("ry") || rx;
        if (w > 0 && h > 0) {
          if (rx > 0 || ry > 0) {
            d = `M ${x + rx} ${y} h ${w - 2 * rx} a ${rx} ${ry} 0 0 1 ${rx} ${ry} v ${h - 2 * ry} a ${rx} ${ry} 0 0 1 -${rx} ${ry} h -${w - 2 * rx} a ${rx} ${ry} 0 0 1 -${rx} -${ry} v -${h - 2 * ry} a ${rx} ${ry} 0 0 1 ${rx} -${ry} Z`;
          } else {
            d = `M ${x} ${y} h ${w} v ${h} h -${w} Z`;
          }
        }
      } else if (tag === "circle") {
        const cx = getNum("cx"), cy = getNum("cy"), r = getNum("r");
        if (r > 0) {
          d = `M ${cx - r} ${cy} a ${r} ${r} 0 1 0 ${2 * r} 0 a ${r} ${r} 0 1 0 -${2 * r} 0 Z`;
        }
      } else if (tag === "ellipse") {
        const cx = getNum("cx"), cy = getNum("cy");
        const rx = getNum("rx"), ry = getNum("ry");
        if (rx > 0 && ry > 0) {
          d = `M ${cx - rx} ${cy} a ${rx} ${ry} 0 1 0 ${2 * rx} 0 a ${rx} ${ry} 0 1 0 -${2 * rx} 0 Z`;
        }
      } else if (tag === "polygon" || tag === "polyline") {
        const pts = (el.getAttribute("points") || "").trim().split(/[\s,]+/).map(Number);
        if (pts.length >= 4) {
          d = `M ${pts[0]} ${pts[1]}`;
          for (let i = 2; i < pts.length - 1; i += 2) {
            d += ` L ${pts[i]} ${pts[i + 1]}`;
          }
          if (tag === "polygon") d += " Z";
        }
      } else if (tag === "line") {
        const x1 = getNum("x1"), y1 = getNum("y1");
        const x2 = getNum("x2"), y2 = getNum("y2");
        d = `M ${x1} ${y1} L ${x2} ${y2}`;
      }

      if (!d || d === "Z") return;

      // Accumulate parent group transforms
      let transforms = [];
      let parent = el;
      while (parent && parent !== svg) {
        if (parent.getAttribute) {
          const t = parent.getAttribute("transform");
          if (t) transforms.unshift(t.trim());
        }
        parent = parent.parentNode;
      }

      const totalTransform = [baseTransform, ...transforms].filter(Boolean).join(" ");

      const rawName = el.getAttribute("data-name") || el.getAttribute("inkscape:label") || el.getAttribute("id") || "";
      const cleanName = rawName.replace(/^path[-_\d]+/i, "").replace(/^svg_[\d]+/i, "").trim();
      const regionName = cleanName || `Shape ${regions.length}`;

      regions.push(R(regionName, [d, totalTransform]));
    });

    return regions.length > 1 ? { regions, outline: outlineOverlay } : null;
  }
}

